"""Generate TypeScript types for event payloads from the Python registry.

    uv run python scripts/gen_types.py            write web/src/events.gen.ts
    uv run python scripts/gen_types.py --check    exit 1 if the file is stale

A test runs the check, so the web app's types cannot drift from the server's.
"""

from __future__ import annotations

import sys
from pathlib import Path

import jimmyhq.kinds  # noqa: F401 - registers the core event kinds
from jimmyhq import modules
from jimmyhq.tape import registry

modules.load()

OUT = Path(__file__).resolve().parents[1] / "web" / "src" / "events.gen.ts"


def _type(schema: dict, defs: dict) -> str:
    if "$ref" in schema:
        return _type(defs[schema["$ref"].rsplit("/", 1)[-1]], defs)
    if "anyOf" in schema:
        return " | ".join(dict.fromkeys(_type(s, defs) for s in schema["anyOf"]))
    if "enum" in schema:
        return " | ".join(repr(v).replace("'", '"') for v in schema["enum"])
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        inner = _type(schema.get("items", {}), defs)
        return f"({inner})[]" if " " in inner else f"{inner}[]"
    if kind == "object":
        props = schema.get("properties")
        if not props:
            extra = schema.get("additionalProperties")
            value = _type(extra, defs) if isinstance(extra, dict) else "unknown"
            return f"Record<string, {value}>"
        required = set(schema.get("required", []))
        fields = [
            f"{name}{'' if name in required else '?'}: {_type(sub, defs)}"
            for name, sub in props.items()
        ]
        return "{ " + "; ".join(fields) + " }"
    return "unknown"


def _name(kind: str) -> str:
    return "".join(part.title().replace("_", "") for part in kind.split("."))


def render() -> str:
    lines = [
        "// Generated by scripts/gen_types.py from the server's event registry.",
        "// Do not edit by hand. Run: uv run python scripts/gen_types.py",
        "",
    ]
    schemas = registry.json_schemas()
    for kind, schema in schemas.items():
        body = _type({**schema, "type": "object"}, schema.get("$defs", {}))
        if body.startswith("Record<"):
            body = "Record<string, never>"
        lines.append(f"export type {_name(kind)} = {body};")
    lines.append("")
    lines.append("export interface EventPayloads {")
    lines.extend(f'  "{kind}": {_name(kind)};' for kind in schemas)
    lines.append("}")
    lines.append("")
    lines.append("export type EventKind = keyof EventPayloads;")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    text = render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != text:
            print(f"{OUT} is stale. Run: uv run python scripts/gen_types.py")
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
